package setting

// qy_groupnote_export.go —— 千夜扩展「模型分组备注」与上游 setting 包之间的唯一耦合面。
//
// 纯新增文件,合并上游时冲突为 0。hook 带 no-op 默认实现,因此扩展未启用
// (甚至整个 qianye 目录被删掉)时说明文案逐位等于上游,调用点无需 nil 判断。
//
// ══════════════ 备注与 options.UserUsableGroups 的 value 是什么关系 ══════════════
//
// 上游 `options.UserUsableGroups` 是一张 map,它的 **key 与 value 承担两件完全不同
// 的事**,而这一点从来没有被写下来过:
//
//	key   全局「哪些模型分组可以被用户选到」的白名单
//	value 那个分组在用户界面上的说明文案(本站有真实内容,如
//	      「浅夜自有分组用户数据,本站均不会留存…」)
//
// 现在 qy_model_groups.note 也是一段"给用户看的说明"。两份文案并存而没人知道
// 哪一份生效,是新的混乱源 —— 所以这里把关系一次性钉死,**不做合并、不做拼接**:
//
//	备注非空  → 备注生效,白名单 value 完全不显示
//	备注为空  → 逐位回落到白名单 value(= 上游今天的行为)
//
// 选"覆盖"而不是"合并"的理由:合并出来的文案没有唯一作者,运营改了一处发现界面上
// 还留着另一半,只能去猜另一半写在哪儿;而拼接的结果长度不可控,令牌下拉里放不下。
// 选"备注优先"而不是"白名单优先"的理由:白名单 value 的编辑器在
// 「用户分组可用的模型分组配置」页,主语是**全局白名单**;备注的编辑器在模型分组
// 登记表上,主语就是**这个模型分组**。谁的主语更贴近这段文案,谁生效。
//
// 管理端两处都必须把这条优先级画出来(备注框旁边显示"当前生效 / 已覆盖白名单说明",
// 白名单那张表上显示"该行说明已被模型分组备注覆盖"),否则省下的推理负担会原样
// 还回去。
//
// ══════════════════════ 实现方必须遵守 ══════════════════════
//
//  1. **零 I/O、零锁、零 context 等待。** QyGroupNote 会被 GetUserUsableGroupsCopy
//     调用,而后者挂在 middleware/auth.go 的令牌分组校验上,每一个带令牌分组的
//     relay 请求调用一次(每次遍历整张白名单)。只允许 atomic.Pointer.Load 与 map 查找。
//  2. **未配置必须返回空串**,不得返回分组名或任何占位文案 —— 空串是"回落上游"的
//     唯一信号,返回分组名会把每一个没写备注的分组的说明都覆盖成它自己的名字。
//  3. 赋值只在 qianye.Init() 发生一次,早于 HTTP 监听与后台协程。
var QyGroupNote = func(groupName string) string { return "" }

// QyDescribeGroup 按上面那条优先级给出一个模型分组的最终说明文案。
//
// 调用点只需把"上游本来会用的那段文案"作为 upstream 传进来,优先级由这里统一持有 ——
// 三处调用点各自写一遍 `if note != "" { … }` 的表现是:某一天有人只改了其中两处,
// 于是同一个分组在令牌页和模型广场上显示两段不同的说明。
func QyDescribeGroup(groupName, upstream string) string {
	if note := QyGroupNote(groupName); note != "" {
		return note
	}
	return upstream
}
